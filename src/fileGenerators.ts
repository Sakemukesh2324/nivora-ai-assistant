import JSZip from "jszip";
import * as XLSX from "xlsx";
import { jsPDF } from "jspdf";

export interface GenerateFileParams {
  format:
    | "pdf"
    | "docx"
    | "xlsx"
    | "pptx"
    | "csv"
    | "txt"
    | "md"
    | "zip"
    | "json"
    | "xml"
    | "html"
    | "css"
    | "js"
    | "ts"
    | "py"
    | "java"
    | "c"
    | "cpp"
    | "sql";
  filename?: string;
  title?: string;
  content: string;
  files?: Array<{ name: string; content: string }>;
}

export interface GeneratedFileResult {
  buffer: Buffer;
  filename: string;
  mimeType: string;
}

export async function generateFile(params: GenerateFileParams): Promise<GeneratedFileResult> {
  const format = params.format.toLowerCase() as GenerateFileParams["format"];
  const title = params.title || "NIVORA Generated Document";
  let filename = params.filename || `nivora-${Date.now()}.${format}`;
  if (!filename.endsWith(`.${format}`)) {
    filename += `.${format}`;
  }

  switch (format) {
    case "csv": {
      // Add UTF-8 BOM for Excel compatibility
      const bom = "\uFEFF";
      const buffer = Buffer.from(bom + params.content, "utf-8");
      return { buffer, filename, mimeType: "text/csv; charset=utf-8" };
    }

    case "txt": {
      const buffer = Buffer.from(params.content, "utf-8");
      return { buffer, filename, mimeType: "text/plain; charset=utf-8" };
    }

    case "md": {
      const buffer = Buffer.from(params.content, "utf-8");
      return { buffer, filename, mimeType: "text/markdown; charset=utf-8" };
    }

    case "xlsx": {
      // Parse content: check if it's CSV-like or JSON table, otherwise line-by-line
      const lines = params.content.split("\n").filter((l) => l.trim().length > 0);
      let rows: any[][] = [];
      try {
        const parsed = JSON.parse(params.content);
        if (Array.isArray(parsed)) {
          if (Array.isArray(parsed[0])) {
            rows = parsed;
          } else if (typeof parsed[0] === "object") {
            const headers = Object.keys(parsed[0]);
            rows.push(headers);
            parsed.forEach((obj) => rows.push(headers.map((h) => obj[h] ?? "")));
          }
        }
      } catch {}

      if (rows.length === 0) {
        rows = lines.map((line) => {
          if (line.includes(",")) {
            return line.split(",").map((c) => c.trim().replace(/^["']|["']$/g, ""));
          }
          if (line.includes("\t")) {
            return line.split("\t").map((c) => c.trim());
          }
          if (line.includes("|")) {
            const cells = line.split("|").map((c) => c.trim()).filter(Boolean);
            if (cells.length > 0 && !cells.every((c) => /^[-:]+$/.test(c))) {
              return cells;
            }
          }
          return [line];
        }).filter((r) => r.length > 0);
      }

      if (rows.length === 0) {
        rows = [[title], [params.content]];
      }

      const ws = XLSX.utils.aoa_to_sheet(rows);
      const wb = XLSX.utils.book_new();
      XLSX.utils.book_append_sheet(wb, ws, "NIVORA Data");
      const buffer = XLSX.write(wb, { type: "buffer", bookType: "xlsx" }) as Buffer;
      return {
        buffer,
        filename,
        mimeType: "application/vnd.openxmlformats-officedocument.spreadsheetml.sheet",
      };
    }

    case "zip": {
      const zip = new JSZip();
      if (params.files && params.files.length > 0) {
        params.files.forEach((f) => {
          zip.file(f.name, f.content);
        });
      } else {
        zip.file("README.md", `# ${title}\n\nGenerated by NIVORA AI Assistant\n\n${params.content}`);
      }
      const buffer = (await zip.generateAsync({ type: "nodebuffer" })) as Buffer;
      return { buffer, filename, mimeType: "application/zip" };
    }

    case "docx": {
      const zip = new JSZip();
      const escapedTitle = escapeXml(title);
      const paragraphs = params.content
        .split("\n")
        .map((p) => `<w:p><w:r><w:t>${escapeXml(p)}</w:t></w:r></w:p>`)
        .join("");

      zip.file(
        "[Content_Types].xml",
        `<?xml version="1.0" encoding="UTF-8" standalone="yes"?>
<Types xmlns="http://schemas.openxmlformats.org/package/2006/content-types">
  <Default Extension="rels" ContentType="application/vnd.openxmlformats-package.relationships+xml"/>
  <Default Extension="xml" ContentType="application/xml"/>
  <Override PartName="/word/document.xml" ContentType="application/vnd.openxmlformats-officedocument.wordprocessingml.document.main+xml"/>
</Types>`
      );

      zip.file(
        "_rels/.rels",
        `<?xml version="1.0" encoding="UTF-8" standalone="yes"?>
<Relationships xmlns="http://schemas.openxmlformats.org/package/2006/relationships">
  <Relationship Id="rId1" Type="http://schemas.openxmlformats.org/officeDocument/2006/relationships/officeDocument" Target="word/document.xml"/>
</Relationships>`
      );

      zip.file(
        "word/document.xml",
        `<?xml version="1.0" encoding="UTF-8" standalone="yes"?>
<w:document xmlns:w="http://schemas.openxmlformats.org/wordprocessingml/2006/main">
  <w:body>
    <w:p>
      <w:pPr><w:jc w:val="center"/></w:pPr>
      <w:r><w:rPr><w:b/><w:sz w:val="36"/></w:rPr><w:t>${escapedTitle}</w:t></w:r>
    </w:p>
    <w:p/>
    ${paragraphs}
    <w:sectPr/>
  </w:body>
</w:document>`
      );

      const buffer = (await zip.generateAsync({ type: "nodebuffer" })) as Buffer;
      return {
        buffer,
        filename,
        mimeType: "application/vnd.openxmlformats-officedocument.wordprocessingml.document",
      };
    }

    case "pptx": {
      const zip = new JSZip();
      const escapedTitle = escapeXml(title);
      const slideText = escapeXml(params.content.slice(0, 500));

      zip.file(
        "[Content_Types].xml",
        `<?xml version="1.0" encoding="UTF-8" standalone="yes"?>
<Types xmlns="http://schemas.openxmlformats.org/package/2006/content-types">
  <Default Extension="rels" ContentType="application/vnd.openxmlformats-package.relationships+xml"/>
  <Default Extension="xml" ContentType="application/xml"/>
  <Override PartName="/ppt/presentation.xml" ContentType="application/vnd.openxmlformats-officedocument.presentationml.presentation.main+xml"/>
  <Override PartName="/ppt/slides/slide1.xml" ContentType="application/vnd.openxmlformats-officedocument.presentationml.slide+xml"/>
</Types>`
      );

      zip.file(
        "_rels/.rels",
        `<?xml version="1.0" encoding="UTF-8" standalone="yes"?>
<Relationships xmlns="http://schemas.openxmlformats.org/package/2006/relationships">
  <Relationship Id="rId1" Type="http://schemas.openxmlformats.org/officeDocument/2006/relationships/officeDocument" Target="ppt/presentation.xml"/>
</Relationships>`
      );

      zip.file(
        "ppt/presentation.xml",
        `<?xml version="1.0" encoding="UTF-8" standalone="yes"?>
<p:presentation xmlns:p="http://schemas.openxmlformats.org/presentationml/2006/main" xmlns:r="http://schemas.openxmlformats.org/officeDocument/2006/relationships">
  <p:sldIdLst>
    <p:sldId id="256" r:id="rId1"/>
  </p:sldIdLst>
</p:presentation>`
      );

      zip.file(
        "ppt/_rels/presentation.xml.rels",
        `<?xml version="1.0" encoding="UTF-8" standalone="yes"?>
<Relationships xmlns="http://schemas.openxmlformats.org/package/2006/relationships">
  <Relationship Id="rId1" Type="http://schemas.openxmlformats.org/officeDocument/2006/relationships/slide" Target="slides/slide1.xml"/>
</Relationships>`
      );

      zip.file(
        "ppt/slides/slide1.xml",
        `<?xml version="1.0" encoding="UTF-8" standalone="yes"?>
<p:sld xmlns:p="http://schemas.openxmlformats.org/presentationml/2006/main" xmlns:a="http://schemas.openxmlformats.org/drawingml/2006/main">
  <p:cSld>
    <p:spTree>
      <p:nvGrpSpPr><p:cNvPr id="1" name=""/><p:cNvGrpSpPr/><p:nvPr/></p:nvGrpSpPr>
      <p:grpSpPr/>
      <p:sp>
        <p:nvSpPr><p:cNvPr id="2" name="Title"/><p:cNvSpPr/><p:nvPr/></p:nvSpPr>
        <p:spPr/>
        <p:txBody>
          <a:bodyPr/>
          <a:p><a:r><a:rPr lang="en-US" sz="3200" b="1"/><a:t>${escapedTitle}</a:t></a:r></a:p>
          <a:p><a:r><a:rPr lang="en-US" sz="1800"/><a:t>${slideText}</a:t></a:r></a:p>
        </p:txBody>
      </p:sp>
    </p:spTree>
  </p:cSld>
</p:sld>`
      );

      const buffer = (await zip.generateAsync({ type: "nodebuffer" })) as Buffer;
      return {
        buffer,
        filename,
        mimeType: "application/vnd.openxmlformats-officedocument.presentationml.presentation",
      };
    }

    case "pdf": {
      try {
        const doc = new jsPDF({
          orientation: "portrait",
          unit: "pt",
          format: "a4",
        });

        const pageWidth = doc.internal.pageSize.getWidth();
        const pageHeight = doc.internal.pageSize.getHeight();
        const margin = 45;
        const maxLineWidth = pageWidth - margin * 2;

        // Title Header
        const cleanTitle = (title || "NIVORA Generated Document").replace(/[\r\n]+/g, " ");
        doc.setFont("helvetica", "bold");
        doc.setFontSize(16);
        doc.setTextColor(33, 37, 41);
        doc.text(cleanTitle, margin, 50);

        // Subheader metadata
        doc.setFont("helvetica", "normal");
        doc.setFontSize(9);
        doc.setTextColor(108, 117, 125);
        doc.text(`Generated by NIVORA AI • ${new Date().toLocaleDateString()}`, margin, 66);

        // Accent divider line
        doc.setDrawColor(108, 99, 255);
        doc.setLineWidth(1.5);
        doc.line(margin, 76, pageWidth - margin, 76);

        // Content
        doc.setFont("courier", "normal");
        doc.setFontSize(9.5);
        doc.setTextColor(40, 40, 45);

        const cleanContent = params.content || "No content provided.";
        const lines = doc.splitTextToSize(cleanContent, maxLineWidth);
        let cursorY = 96;
        const lineHeight = 13.5;

        for (let i = 0; i < lines.length; i++) {
          if (cursorY + lineHeight > pageHeight - margin) {
            doc.addPage();
            cursorY = margin + 15;
          }
          doc.text(lines[i], margin, cursorY);
          cursorY += lineHeight;
        }

        const arrayBuffer = doc.output("arraybuffer");
        return {
          buffer: Buffer.from(arrayBuffer),
          filename,
          mimeType: "application/pdf",
        };
      } catch (pdfErr) {
        console.warn("[NIVORA PDF] jsPDF generation fallback:", pdfErr);
        // Fallback minimal standard PDF
        const cleanTitle = (title || "NIVORA Document").replace(/[\(\)\\]/g, "");
        const lines = params.content.split("\n").slice(0, 35);
        let streamCommands = `BT\n/F1 18 Tf\n50 740 Td\n(${cleanTitle}) Tj\nET\n`;
        let y = 705;
        lines.forEach((line) => {
          const safeLine = line.slice(0, 95).replace(/[\(\)\\]/g, "");
          if (safeLine.trim()) {
            streamCommands += `BT\n/F1 11 Tf\n50 ${y} Td\n(${safeLine}) Tj\nET\n`;
            y -= 18;
          } else {
            y -= 10;
          }
        });

        const streamLen = Buffer.byteLength(streamCommands);
        let pdf = "%PDF-1.4\n";
        const offsets: number[] = [];

        function addObj(str: string) {
          offsets.push(Buffer.byteLength(pdf));
          pdf += str + "\n";
        }

        addObj("1 0 obj\n<< /Type /Catalog /Pages 2 0 R >>\nendobj");
        addObj("2 0 obj\n<< /Type /Pages /Kids [3 0 R] /Count 1 >>\nendobj");
        addObj(
          "3 0 obj\n<< /Type /Page /Parent 2 0 R /MediaBox [0 0 612 792] /Resources << /Font << /F1 4 0 R >> >> /Contents 5 0 R >>\nendobj"
        );
        addObj("4 0 obj\n<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>\nendobj");
        addObj(`5 0 obj\n<< /Length ${streamLen} >>\nstream\n${streamCommands}\nendstream\nendobj`);

        const xrefOffset = Buffer.byteLength(pdf);
        pdf += "xref\n0 6\n0000000000 65535 f \n";
        for (const off of offsets) {
          pdf += off.toString().padStart(10, "0") + " 00000 n \n";
        }
        pdf += `trailer\n<< /Size 6 /Root 1 0 R >>\nstartxref\n${xrefOffset}\n%%EOF`;

        return {
          buffer: Buffer.from(pdf, "binary"),
          filename,
          mimeType: "application/pdf",
        };
      }
    }

    case "json": {
      let formatted = params.content;
      try {
        const parsed = JSON.parse(params.content);
        formatted = JSON.stringify(parsed, null, 2);
      } catch {
        formatted = JSON.stringify({ title, content: params.content, generatedBy: "NIVORA AI" }, null, 2);
      }
      const buffer = Buffer.from(formatted, "utf-8");
      return { buffer, filename, mimeType: "application/json; charset=utf-8" };
    }

    case "xml": {
      const buffer = Buffer.from(params.content, "utf-8");
      return { buffer, filename, mimeType: "application/xml; charset=utf-8" };
    }

    case "html": {
      const buffer = Buffer.from(params.content, "utf-8");
      return { buffer, filename, mimeType: "text/html; charset=utf-8" };
    }

    case "css": {
      const buffer = Buffer.from(params.content, "utf-8");
      return { buffer, filename, mimeType: "text/css; charset=utf-8" };
    }

    case "js": {
      const buffer = Buffer.from(params.content, "utf-8");
      return { buffer, filename, mimeType: "application/javascript; charset=utf-8" };
    }

    case "ts": {
      const buffer = Buffer.from(params.content, "utf-8");
      return { buffer, filename, mimeType: "text/typescript; charset=utf-8" };
    }

    case "py": {
      const buffer = Buffer.from(params.content, "utf-8");
      return { buffer, filename, mimeType: "text/x-python; charset=utf-8" };
    }

    case "java": {
      const buffer = Buffer.from(params.content, "utf-8");
      return { buffer, filename, mimeType: "text/x-java; charset=utf-8" };
    }

    case "c": {
      const buffer = Buffer.from(params.content, "utf-8");
      return { buffer, filename, mimeType: "text/x-c; charset=utf-8" };
    }

    case "cpp": {
      const buffer = Buffer.from(params.content, "utf-8");
      return { buffer, filename, mimeType: "text/x-c++src; charset=utf-8" };
    }

    case "sql": {
      const buffer = Buffer.from(params.content, "utf-8");
      return { buffer, filename, mimeType: "application/sql; charset=utf-8" };
    }

    default: {
      const buffer = Buffer.from(params.content, "utf-8");
      return { buffer, filename, mimeType: "application/octet-stream" };
    }
  }
}

function escapeXml(unsafe: string): string {
  return (unsafe || "")
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;")
    .replace(/'/g, "&apos;");
}
